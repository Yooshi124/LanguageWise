-- Retire the release-zero sample table from both fresh and existing volumes.
DROP TABLE IF EXISTS SampleItems;

CREATE TABLE IF NOT EXISTS Users (
    Id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username      TEXT NOT NULL UNIQUE,
    Password      TEXT NOT NULL,
    LastLogin     DATE,
    CurrentStreak INTEGER NOT NULL DEFAULT 0,
    ProfilePictureStorageKey  TEXT,
    ProfilePictureFileName    TEXT,
    ProfilePictureContentType TEXT,
    ProfilePictureSizeBytes   BIGINT,
    ProfilePictureUploadedAt  TIMESTAMP WITH TIME ZONE,
    IsAdmin       BOOLEAN NOT NULL DEFAULT FALSE
);

ALTER TABLE Users ADD COLUMN IF NOT EXISTS IsAdmin BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS AdminSettings (
    Name      TEXT PRIMARY KEY,
    IsEnabled BOOLEAN NOT NULL DEFAULT FALSE
);
